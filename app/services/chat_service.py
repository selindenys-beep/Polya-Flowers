def generate_reply(user_text: str, history: list[dict] | None = None) -> str:
    """Формує відповідь клієнту через Claude Haiku (мовою клієнта)."""
    if not config.ANTHROPIC_API_KEY:
        return ("Дякуємо за повідомлення! 💐 Ми зовсім скоро відповімо. "
                "А поки можете переглянути наші букети на сайті " + WEBSITE_URL)

    client = Anthropic(api_key=config.ANTHROPIC_API_KEY)
    system = SYSTEM_PROMPT + "\n\n" + DELIVERY_INFO + "\n\n" + PAYMENT_INFO
    messages = (history or []) + [{"role": "user", "content": user_text}]

    message = client.messages.create(
        model=config.CLAUDE_CHAT_MODEL,
        max_tokens=600,
        system=system,
        messages=messages,
    )
    return "".join(b.text for b in message.content if b.type == "text").strip()
