"""Спілкування з клієнтами через Claude Haiku (швидкі відповіді українською).

Це «мозок» бота: приймає повідомлення клієнта і формує відповідь.
Системний промт нижче — СТАРТОВИЙ, його легко доповнювати (умови доставки,
асортимент, акції тощо) у міру появи інформації.
"""
from __future__ import annotations

from anthropic import Anthropic

from app import config

# ─────────────────────────────────────────────────────────────
# Стартовий системний промт бота. Редагується вільно.
# ─────────────────────────────────────────────────────────────
SYSTEM_PROMPT = """Ти — доброзичливий помічник невеликого сімейного магазину «Polya Flowers».
Ми робимо квіти та букети ручної роботи. Ти спілкуєшся з клієнтами в Telegram українською мовою.

Стиль спілкування:
- Тепло, ввічливо, щиро, як турботлива людина, а не робот.
- Коротко й по суті; доречні емодзі 💐 у міру.
- Звертайся на «ви».

Що ти вмієш:
- Відповідати на запитання про букети, склад, догляд за квітами.
- Допомогти обрати букет під привід (день народження, побачення, подяка).
- Пояснити варіанти доставки та оплати (див. нижче).
- Підказати, як зробити замовлення: клієнт пише, який букет і на яку дату потрібен.

Важливі правила:
- Ціна кожного букета вказана у пості з фото. Якщо клієнт питає ціну конкретного товару,
  а ти її не знаєш — попроси уточнити, який саме букет цікавить.
- Не вигадуй наявність чи характеристики, яких не знаєш. Краще чесно сказати, що уточниш.
- Якщо питання складне або стосується індивідуального замовлення — запропонуй, що майстриня
  зв'яжеться особисто, і попроси зручний спосіб контакту.
"""

# Стартова інформація про доставку (легко змінити).
DELIVERY_INFO = """🚚 Доставка по Україні:
• «Нова Пошта» — по всій Україні, зазвичай 1–2 дні. Оплата доставки за тарифами перевізника.
• Місцева доставка по місту — узгоджуємо час особисто.
• Самовивіз — за домовленістю.

Щоб оформити доставку, напишіть, будь ласка, місто та бажану дату — і ми все узгодимо 💐"""

PAYMENT_INFO = """💳 Оплата:
Оплатити можна за посиланням (кнопка «Оплатити» під товаром) —
підтримується Apple Pay / Google Pay та звичайна картка."""


def generate_reply(user_text: str, history: list[dict] | None = None) -> str:
    """Формує відповідь клієнту через Claude Haiku.

    history — необов'язковий список попередніх реплік у форматі
    [{"role": "user"|"assistant", "content": "..."}].
    """
    if not config.ANTHROPIC_API_KEY:
        return ("Дякуємо за повідомлення! 💐 Ми зовсім скоро відповімо. "
                "А поки можете переглянути наші букети вище.")

    client = Anthropic(api_key=config.ANTHROPIC_API_KEY)
    system = SYSTEM_PROMPT + "\n\n" + DELIVERY_INFO + "\n\n" + PAYMENT_INFO
    messages = (history or []) + [{"role": "user", "content": user_text}]

    message = client.messages.create(
        model=config.CLAUDE_CHAT_MODEL,
        max_tokens=600,
        system=system,
        messages=messages,
    )
    return "".join(b.text for b in message.content if b.type == "text").strip()
